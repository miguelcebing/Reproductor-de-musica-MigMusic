const dictionaries: Record<Language, Record<MessageKey, string>> = { es, en };

/** Values interpolated into `{placeholder}` slots. */
export type MessageParams = Readonly<Record<string, string | number>>;

/** Translate `key`, then replace `{name}` placeholders with `params`. */
export function translate(language: Language, key: MessageKey, params?: MessageParams): string {
  const template = dictionaries[language][key] ?? dictionaries.es[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
  );
}
